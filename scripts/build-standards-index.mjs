// Regenerates src/lib/standardsIndex.js from src/lib/standardsData.js.
//
//     node scripts/build-standards-index.mjs      (or: npm run standards:index)
//
// The data file is the whole Missouri catalogue, half a megabyte of
// statements, and the board must not pay for it on every first paint.
// The index is the light part every page needs -- which frameworks
// exist, what they are called, one sample code for the store card --
// and the data file is loaded on demand (see loadStandardsCatalog in
// src/lib/standards.js). Run this whenever standardsData.js changes;
// the app imports the index, never the data, at module load.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = await import(path.join(here, "..", "src", "lib", "standardsData.js").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));

// Same order the store shows: K-5 first, then the 6-12 subjects.
const all = [
  ...(data.MISSOURI_K5_FRAMEWORKS || []),
  ...(data.MISSOURI_SCIENCE_FRAMEWORKS || []),
  ...(data.MISSOURI_MATH_FRAMEWORKS || []),
  ...(data.MISSOURI_ELA_FRAMEWORKS || []),
  ...(data.MISSOURI_SOCIAL_STUDIES_FRAMEWORKS || []),
];
const seen = new Set();
const index = all.map(f => {
  if (seen.has(f.id)) throw new Error(`duplicate framework id ${f.id}`);
  seen.add(f.id);
  return { id: f.id, label: f.label, short: f.short, subject: f.subject, band: f.band, blurb: f.blurb, source: f.source, sampleCode: f.standards[0]?.code || "", count: f.standards.length };
});

const out = `// GENERATED by scripts/build-standards-index.mjs from standardsData.js.
// Do not edit by hand; edit the data and regenerate. This is the light
// list of frameworks the app loads up front; the standards themselves
// are loaded on demand (loadStandardsCatalog in standards.js).
export const STANDARDS_FRAMEWORK_INDEX = ${JSON.stringify(index, null, 2)};
`;
writeFileSync(path.join(here, "..", "src", "lib", "standardsIndex.js"), out);
console.log(`standardsIndex.js: ${index.length} frameworks, ${index.reduce((n, f) => n + f.count, 0)} standards`);
